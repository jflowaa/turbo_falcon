-- Case-insensitive filter searches use leading-wildcard LIKE, which only a
-- trigram index can accelerate.
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE job_threads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL,
    title TEXT NOT NULL,
    created TIMESTAMP(0),
    postings BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT job_threads_item_id_positive_check CHECK (item_id > 0),
    CONSTRAINT job_threads_postings_nonnegative_check CHECK (postings >= 0)
);
CREATE UNIQUE INDEX job_threads_item_id_index ON job_threads (item_id);

CREATE TABLE job_postings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL,
    thread_id BIGINT NOT NULL REFERENCES job_threads (item_id) ON DELETE CASCADE,
    "user" TEXT NOT NULL,
    text TEXT NOT NULL,
    summarized BOOLEAN NOT NULL DEFAULT FALSE,
    summarized_text TEXT,
    summarized_at TIMESTAMP(0),
    "timestamp" TIMESTAMP(0),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT job_postings_item_id_positive_check CHECK (item_id > 0),
    CONSTRAINT job_postings_thread_id_positive_check CHECK (thread_id > 0),
    CONSTRAINT job_postings_summary_text_check CHECK (summarized = FALSE OR summarized_text IS NOT NULL)
);
CREATE UNIQUE INDEX job_postings_item_id_index ON job_postings (item_id);

-- The LiveView loads one thread's postings and orders them newest first. The
-- leading thread_id column also covers foreign-key lookups, so no separate
-- thread_id index is needed.
CREATE INDEX job_postings_thread_id_timestamp_index
    ON job_postings (thread_id, "timestamp" DESC);

-- The summarization producer polls this predicate every few seconds.
CREATE INDEX job_postings_pending_idx ON job_postings ("timestamp" DESC)
    WHERE summarized = FALSE AND deleted = FALSE;

-- The filter box runs case-insensitive substring searches over posting text.
CREATE INDEX job_postings_text_trgm_idx
    ON job_postings USING GIN (LOWER(text) gin_trgm_ops);

-- The app role owns this database and must be the only non-superuser allowed to
-- connect to it. This also runs for the local test database.
DO $$
BEGIN
    EXECUTE format('REVOKE ALL ON DATABASE %I FROM PUBLIC', current_database());
    EXECUTE format('GRANT CONNECT ON DATABASE %I TO %I', current_database(), current_user);
END
$$;

